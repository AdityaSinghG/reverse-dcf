"""Audit a recalculated workbook against the modelling rules.

Usage:  python -m src.audit_excel path/to/recalculated.xlsx

Run it on the LibreOffice-recalculated copy: it needs cached values to see error cells. Rules:

  HARDCODE_IN_FORMULA   numeric literal other than 0 or 1 inside a formula (constants belong on Inputs)
  ERROR_VALUE           cell evaluates to #REF! #DIV/0! #NAME? #VALUE! #N/A #NUM! #NULL!
  BROKEN_REFERENCE      formula text contains #REF!
  INCONSISTENT_ROW      an interior cell of a run of formulas breaks the row's pattern (compared in
                        relative form, so a copied-across formula is "the same")
  HARDCODE_OUTSIDE_INPUTS  a typed number off the Inputs tab that is not a labelled static value
                        (grey italic AND its sheet says "static, generated by")
  INPUT_MISSING_SOURCE  Inputs row with a value but no source or no source date
  INPUT_NOT_BLUE        Inputs value not in blue font
  UNLINKED_INPUT        Inputs value that no formula references (dead input)
  BLUE_FORMULA          formula in blue font (blue is reserved for inputs)
  FORMULA_ON_INPUTS     formula on the Inputs tab (inputs must be typed values)
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

import openpyxl
from openpyxl.formula import Tokenizer
from openpyxl.formula.tokenizer import Token
from openpyxl.formula.translate import Translator
from openpyxl.utils import get_column_letter, range_boundaries

ERRORS = {"#REF!", "#DIV/0!", "#NAME?", "#VALUE!", "#N/A", "#NUM!", "#NULL!"}
ALLOWED_LITERALS = {0.0, 1.0}
INPUTS = "Inputs"
STATIC_GREY = "595959"
BLUE = "0000FF"
VALUE_COL, SOURCE_COL, DATE_COL = "C", "E", "F"
MIN_RUN = 4          # a row needs at least this many consecutive formulas to have a "pattern"
MIN_DOMINANT = 3


@dataclass(frozen=True)
class Finding:
    rule: str
    severity: str            # ERROR | WARN
    sheet: str
    cell: str
    detail: str


@dataclass
class AuditReport:
    path: str
    findings: list = field(default_factory=list)
    counts: dict = field(default_factory=dict)

    @property
    def errors(self):
        return [f for f in self.findings if f.severity == "ERROR"]

    @property
    def warnings(self):
        return [f for f in self.findings if f.severity == "WARN"]

    def by_rule(self, rule):
        return [f for f in self.findings if f.rule == rule]

    def text(self) -> str:
        c = self.counts
        L = [f"AUDIT REPORT: {self.path}",
             f"  sheets {c['sheets']}, formula cells {c['formulas']}, typed numbers {c['numbers']}, "
             f"Inputs rows {c['input_rows']}",
             f"  ERRORS {len(self.errors)}   WARNINGS {len(self.warnings)}"]
        rules = sorted({f.rule for f in self.findings})
        for rule in RULES:
            hits = self.by_rule(rule)
            L.append(f"  [{'FAIL' if any(h.severity == 'ERROR' for h in hits) else ('WARN' if hits else ' ok ')}] "
                     f"{rule}: {len(hits)}")
            for h in hits[:25]:
                L.append(f"        {h.sheet}!{h.cell}  {h.detail}")
            if len(hits) > 25:
                L.append(f"        ... {len(hits) - 25} more")
        L.append("RESULT: " + ("CLEAN" if not self.findings else ("FAILED" if self.errors else "PASSED WITH WARNINGS")))
        return "\n".join(L)

    __str__ = text


RULES = ["HARDCODE_IN_FORMULA", "ERROR_VALUE", "BROKEN_REFERENCE", "INCONSISTENT_ROW", "HARDCODE_OUTSIDE_INPUTS",
         "INPUT_MISSING_SOURCE", "INPUT_NOT_BLUE", "UNLINKED_INPUT", "BLUE_FORMULA", "FORMULA_ON_INPUTS"]


def _rgb(cell) -> str | None:
    col = cell.font.color if cell.font else None
    if col is None or col.type != "rgb" or not col.rgb:
        return None
    return str(col.rgb)[-6:].upper()


def _is_formula(v) -> bool:
    return isinstance(v, str) and v.startswith("=")


def _tokens(formula: str):
    try:
        return Tokenizer(formula).items
    except Exception:
        return []


def _relative(formula: str, col: int, row: int) -> str | None:
    """Formula moved to a fixed far-right anchor: identical relative structure -> identical text."""
    try:
        return Translator(formula, origin=f"{get_column_letter(col)}{row}").translate_formula(f"AZ{row}")
    except Exception:
        return None


def _input_refs(formula: str, refs: set):
    """Add every Inputs cell a formula touches (ranges expanded)."""
    for t in _tokens(formula):
        if t.type == Token.OPERAND and t.subtype == Token.RANGE and "!" in t.value:
            sheet, rng = t.value.rsplit("!", 1)
            if sheet.strip("'") != INPUTS:
                continue
            try:
                c1, r1, c2, r2 = range_boundaries(rng.replace("$", ""))
            except Exception:
                continue
            for r in range(r1, r2 + 1):
                for c in range(c1, c2 + 1):
                    refs.add((r, c))


def audit(path: str | Path) -> AuditReport:
    path = Path(path)
    wf = openpyxl.load_workbook(path)
    wv = openpyxl.load_workbook(path, data_only=True)
    rep = AuditReport(str(path))
    add = lambda rule, sev, sh, cell, detail: rep.findings.append(Finding(rule, sev, sh, cell, detail))
    n_formulas = n_numbers = 0
    input_refs: set = set()

    for ws in wf.worksheets:
        vs = wv[ws.title]
        static_sheet = any(isinstance(c.value, str) and "static, generated by" in c.value.lower()
                           for row in ws.iter_rows() for c in row)
        # ---- per-cell rules
        for row in ws.iter_rows():
            for c in row:
                v = c.value
                if v is None:
                    continue
                if _is_formula(v):
                    n_formulas += 1
                    if ws.title == INPUTS:
                        add("FORMULA_ON_INPUTS", "ERROR", ws.title, c.coordinate, v[:60])
                    if _rgb(c) == BLUE:
                        add("BLUE_FORMULA", "WARN", ws.title, c.coordinate, "formula in blue font")
                    if "#ref!" in v.lower():        # LibreOffice rewrites the case on save
                        add("BROKEN_REFERENCE", "ERROR", ws.title, c.coordinate, v[:80])
                    for t in _tokens(v):
                        if t.type == Token.OPERAND and t.subtype == Token.NUMBER:
                            try:
                                lit = float(t.value)
                            except ValueError:
                                continue
                            if lit not in ALLOWED_LITERALS:
                                add("HARDCODE_IN_FORMULA", "ERROR", ws.title, c.coordinate,
                                    f"literal {t.value} in {v[:70]}")
                    _input_refs(v, input_refs)
                    cached = vs[c.coordinate].value
                    if isinstance(cached, str) and cached in ERRORS:
                        add("ERROR_VALUE", "ERROR", ws.title, c.coordinate, f"{cached} from {v[:60]}")
                elif isinstance(v, str) and v in ERRORS:
                    add("ERROR_VALUE", "ERROR", ws.title, c.coordinate, v)
                elif isinstance(v, (int, float)) and not isinstance(v, bool):
                    n_numbers += 1
                    if ws.title != INPUTS:
                        is_static = _rgb(c) == STATIC_GREY and static_sheet
                        if not is_static:
                            add("HARDCODE_OUTSIDE_INPUTS", "ERROR", ws.title, c.coordinate,
                                f"typed number {v} (move it to Inputs or mark it static)")
        # ---- inconsistent formulas across a row
        for row in ws.iter_rows():
            cells = [(c.column, _relative(c.value, c.column, c.row)) for c in row if _is_formula(c.value)]
            cells = [(col, rel) for col, rel in cells if rel is not None]
            run: list = []
            for item in cells + [(None, None)]:
                if run and (item[0] is None or item[0] != run[-1][0] + 1):
                    if len(run) >= MIN_RUN:
                        dom, dom_n = Counter(rel for _, rel in run).most_common(1)[0]
                        if dom_n >= MIN_DOMINANT:
                            for col, rel in run[1:-1]:                     # interior cells only
                                if rel != dom:
                                    coord = f"{get_column_letter(col)}{row[0].row}"
                                    add("INCONSISTENT_ROW", "ERROR", ws.title, coord,
                                        f"differs from the row pattern: {ws[coord].value[:70]}")
                    run = []
                if item[0] is not None:
                    run.append(item)

    # ---- Inputs sheet rules
    n_input_rows = 0
    if INPUTS in wf.sheetnames:
        wi = wf[INPUTS]
        for r in range(5, wi.max_row + 1):
            val = wi[f"{VALUE_COL}{r}"]
            if val.value is None or val.value == "":
                continue
            n_input_rows += 1
            if _is_formula(val.value):
                continue
            src, dte = wi[f"{SOURCE_COL}{r}"].value, wi[f"{DATE_COL}{r}"].value
            if not src or not str(src).strip():
                add("INPUT_MISSING_SOURCE", "ERROR", INPUTS, f"{SOURCE_COL}{r}", f"no source for {wi[f'B{r}'].value!r}")
            if not dte or not str(dte).strip():
                add("INPUT_MISSING_SOURCE", "ERROR", INPUTS, f"{DATE_COL}{r}", f"no source date for {wi[f'B{r}'].value!r}")
            if _rgb(val) != BLUE:
                add("INPUT_NOT_BLUE", "ERROR", INPUTS, val.coordinate, f"font colour {_rgb(val)}")
            if (r, openpyxl.utils.column_index_from_string(VALUE_COL)) not in input_refs:
                add("UNLINKED_INPUT", "WARN", INPUTS, val.coordinate,
                    f"{wi[f'A{r}'].value or wi[f'B{r}'].value!r} is not referenced by any formula")
    rep.counts = {"sheets": len(wf.sheetnames), "formulas": n_formulas, "numbers": n_numbers, "input_rows": n_input_rows}
    return rep


def main(argv=None):
    argv = argv or sys.argv[1:]
    if not argv:
        raise SystemExit("usage: python -m src.audit_excel <recalculated.xlsx>")
    rep = audit(argv[0])
    print(rep.text())
    return 1 if rep.errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
