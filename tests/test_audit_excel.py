"""The audit must catch deliberately planted defects, and stay quiet on a clean workbook."""
import openpyxl
import pytest
from openpyxl.styles import Font

from src import audit_excel as au

BLUE, STATIC = Font(color="0000FF"), Font(color="595959", italic=True)


def make_clean():
    wb = openpyxl.Workbook()
    inp = wb.active
    inp.title = "Inputs"
    inp["A4"], inp["B4"], inp["C4"], inp["E4"], inp["F4"] = "Key", "Label", "Value", "Source", "Date"
    for r, (k, v) in enumerate([("g", 0.05), ("base", 100.0), ("step", 10.0)], start=5):
        inp[f"A{r}"], inp[f"B{r}"] = k, k
        inp[f"C{r}"] = v
        inp[f"C{r}"].font = BLUE
        inp[f"E{r}"], inp[f"F{r}"] = "TEST FIXTURE", "2025-01-01"
    ws = wb.create_sheet("Calc")
    ws["A1"] = "Row of consistent formulas"
    ws["B2"] = "=Inputs!$C$6"
    for i in range(3, 9):                       # C2..H2: each = previous + step
        ws.cell(2, i).value = f"={openpyxl.utils.get_column_letter(i - 1)}2+Inputs!$C$7"
    ws["A3"] = "growth"
    ws["B3"] = "=B2*(1+Inputs!$C$5)"
    return wb


def save(wb, tmp_path, name="wb.xlsx"):
    p = tmp_path / name
    wb.save(p)
    return p


def kinds(rep):
    return {(f.rule, f.sheet, f.cell) for f in rep.findings}


def test_clean_workbook_has_no_findings(tmp_path):
    rep = au.audit(save(make_clean(), tmp_path))
    assert rep.findings == [], rep.text()


def test_catches_hardcode_inside_formula(tmp_path):
    wb = make_clean()
    wb["Calc"]["B3"] = "=B2*1.18"
    rep = au.audit(save(wb, tmp_path))
    hits = rep.by_rule("HARDCODE_IN_FORMULA")
    assert [h.cell for h in hits] == ["B3"] and "1.18" in hits[0].detail
    assert rep.errors


def test_zero_and_one_are_not_hardcodes(tmp_path):
    wb = make_clean()
    wb["Calc"]["B3"] = "=IF(B2>0,MAX(B2,0)*(1+Inputs!$C$5),1)"
    assert au.audit(save(wb, tmp_path)).by_rule("HARDCODE_IN_FORMULA") == []


def test_catches_broken_reference(tmp_path):
    wb = make_clean()
    wb["Calc"]["B3"] = "=B2*#REF!"
    rep = au.audit(save(wb, tmp_path))
    assert ("BROKEN_REFERENCE", "Calc", "B3") in kinds(rep)


def test_catches_error_value(tmp_path):
    wb = make_clean()
    wb["Calc"]["B4"] = "#DIV/0!"
    rep = au.audit(save(wb, tmp_path))
    assert ("ERROR_VALUE", "Calc", "B4") in kinds(rep)


def test_catches_inconsistent_formula_in_row(tmp_path):
    wb = make_clean()
    wb["Calc"]["E2"] = "=D2*2+Inputs!$C$7"      # interior cell breaks the pattern (and adds a literal)
    rep = au.audit(save(wb, tmp_path))
    assert [h.cell for h in rep.by_rule("INCONSISTENT_ROW")] == ["E2"]


def test_inconsistency_without_literal_still_caught(tmp_path):
    wb = make_clean()
    wb["Calc"]["E2"] = "=D2-Inputs!$C$7"        # sign flip only: no literal to catch it by
    rep = au.audit(save(wb, tmp_path))
    assert [h.cell for h in rep.by_rule("INCONSISTENT_ROW")] == ["E2"]
    assert rep.by_rule("HARDCODE_IN_FORMULA") == []


def test_edge_cells_may_start_a_row_differently(tmp_path):
    rep = au.audit(save(make_clean(), tmp_path))       # B2 differs from C2..H2 by design
    assert rep.by_rule("INCONSISTENT_ROW") == []


def test_catches_typed_number_outside_inputs_but_allows_labelled_static(tmp_path):
    wb = make_clean()
    wb["Calc"]["B5"] = 42
    rep = au.audit(save(wb, tmp_path))
    assert [h.cell for h in rep.by_rule("HARDCODE_OUTSIDE_INPUTS")] == ["B5"]
    # a grey static value on a sheet that says where it came from is allowed
    wb = make_clean()
    wb["Calc"]["A9"] = "static, generated by src/sensitivity.py"
    wb["Calc"]["B5"] = 42
    wb["Calc"]["B5"].font = STATIC
    assert au.audit(save(wb, tmp_path, "s.xlsx")).by_rule("HARDCODE_OUTSIDE_INPUTS") == []
    # grey without the label is still a hardcode
    wb = make_clean()
    wb["Calc"]["B5"] = 42
    wb["Calc"]["B5"].font = STATIC
    assert au.audit(save(wb, tmp_path, "u.xlsx")).by_rule("HARDCODE_OUTSIDE_INPUTS")


def test_catches_input_missing_source_and_date(tmp_path):
    wb = make_clean()
    wb["Inputs"]["E6"] = None
    wb["Inputs"]["F7"] = None
    rep = au.audit(save(wb, tmp_path))
    assert {h.cell for h in rep.by_rule("INPUT_MISSING_SOURCE")} == {"E6", "F7"}


def test_catches_unlinked_input(tmp_path):
    wb = make_clean()
    wb["Inputs"]["A8"], wb["Inputs"]["B8"], wb["Inputs"]["C8"] = "orphan", "orphan", 7.0
    wb["Inputs"]["C8"].font = BLUE
    wb["Inputs"]["E8"], wb["Inputs"]["F8"] = "TEST", "2025-01-01"
    rep = au.audit(save(wb, tmp_path))
    assert [h.cell for h in rep.by_rule("UNLINKED_INPUT")] == ["C8"]
    assert not rep.errors                                   # warning, not failure


def test_range_reference_counts_as_linked(tmp_path):
    wb = make_clean()
    wb["Calc"]["B6"] = "=SUM(Inputs!C5:C7)"
    assert au.audit(save(wb, tmp_path)).by_rule("UNLINKED_INPUT") == []


def test_catches_colour_convention_breaks(tmp_path):
    wb = make_clean()
    wb["Calc"]["B3"].font = BLUE
    wb["Inputs"]["C5"].font = Font(color="000000")
    rep = au.audit(save(wb, tmp_path))
    assert ("BLUE_FORMULA", "Calc", "B3") in kinds(rep)
    assert ("INPUT_NOT_BLUE", "Inputs", "C5") in kinds(rep)


def test_formula_on_inputs_flagged(tmp_path):
    wb = make_clean()
    wb["Inputs"]["C6"] = "=C5*2"
    assert ("FORMULA_ON_INPUTS", "Inputs", "C6") in kinds(au.audit(save(wb, tmp_path)))


def test_report_text_and_exit_code(tmp_path, capsys):
    wb = make_clean()
    wb["Calc"]["B3"] = "=B2*1.18"
    p = save(wb, tmp_path)
    assert au.main([str(p)]) == 1
    out = capsys.readouterr().out
    assert "HARDCODE_IN_FORMULA: 1" in out and "RESULT: FAILED" in out
    assert au.main([str(save(make_clean(), tmp_path, "c.xlsx"))]) == 0


def test_broken_reference_detected_in_any_case(tmp_path):
    wb = make_clean()
    wb["Calc"]["B3"] = "=B2+#ref!"           # LibreOffice writes it lower-case after a round trip
    assert ("BROKEN_REFERENCE", "Calc", "B3") in kinds(au.audit(save(wb, tmp_path)))
