"""Build the workbook from the TEST fixture, recalculate with LibreOffice, and compare to Python.
Skipped (not silently passed) if LibreOffice is not installed."""
import copy
from pathlib import Path

import openpyxl
import pandas as pd
import pytest

from src import audit_excel as au, build_excel as be
from tests.fixture_bundle import make_bundle

pytestmark = pytest.mark.skipif(not Path(be.SOFFICE).exists(), reason="LibreOffice not installed")

VARIANTS = {"end_year_constant": dict(mid_year=False, profile="constant"),
            "mid_year_constant": dict(mid_year=True, profile="constant"),
            "end_year_fade": dict(mid_year=False, profile="linear_fade"),
            "mid_year_fade": dict(mid_year=True, profile="linear_fade")}


@pytest.fixture(scope="module", params=list(VARIANTS))
def built(request, tmp_path_factory):
    d = tmp_path_factory.mktemp(request.param)
    bundle = make_bundle(n_sims=1500, **VARIANTS[request.param])
    info = be.build_workbook(bundle, d / "m.xlsx")
    rec = be.recalculate(d / "m.xlsx", d / "rec")
    return request.param, info, rec


def test_excel_matches_python_cell_by_cell(built):
    name, info, rec = built
    cmp_ = be.verify(rec, info, rel_tol=1e-3)
    bad = cmp_[~cmp_["ok"]]
    assert len(cmp_) > 100
    assert bad.empty, f"{name}: {len(bad)} cells differ beyond 0.1%\n{bad.to_string()}"
    # and it is far tighter than 0.1%: same arithmetic
    assert cmp_["rel_diff"].max() < 1e-9


def test_value_per_share_agrees(built):
    _, info, rec = built
    wb = openpyxl.load_workbook(rec, data_only=True)
    xl = be._cell(wb, info.cells["fb"]["vps"])
    assert xl == pytest.approx(info.python["res"].value_per_share, rel=1e-3)


def test_checks_tab_has_no_failures(built):
    _, info, rec = built
    wb = openpyxl.load_workbook(rec, data_only=True)
    lo, hi = info.cells["checks_range"]
    statuses = [wb["Checks"][f"E{r}"].value for r in range(lo, hi + 1)]
    assert "FAIL" not in statuses, [(r, wb["Checks"][f"B{r}"].value) for r, s in zip(range(lo, hi + 1), statuses) if s == "FAIL"]
    assert all(s in ("PASS", "REVIEW") for s in statuses)
    assert be._cell(wb, info.cells["overall"]) in ("ALL PASS", "PASS WITH REVIEW ITEMS")


def test_reverse_blocks_reproduce_price(built):
    _, info, rec = built
    wb = openpyxl.load_workbook(rec, data_only=True)
    assert set(info.cells["reverse_blocks"]) == {"revenue_cagr", "terminal_ebit_margin", "wacc"}
    for k, blk in info.cells["reverse_blocks"].items():
        v = be._cell(wb, blk["vps"])
        assert v == pytest.approx(info.python["price"], rel=1e-3), k


def test_audit_is_clean_on_built_workbook(built):
    _, _, rec = built
    rep = au.audit(rec)
    assert rep.findings == [], rep.text()


def test_verify_flags_a_wrong_python_number(built):
    _, info, rec = built
    tampered = copy.copy(info)
    label, addr, v = info.expected[10]
    tampered.expected = [(label, addr, v * 1.01)] + info.expected[:10] + info.expected[11:]
    cmp_ = be.verify(rec, tampered)
    assert (~cmp_["ok"]).sum() == 1 and cmp_[~cmp_["ok"]].iloc[0]["item"] == label


def test_workbook_structure_and_conventions(built):
    _, info, rec = built
    wb = openpyxl.load_workbook(info.path)
    assert wb.sheetnames == be.SHEETS
    inputs = wb["Inputs"]
    blue = [c for row in inputs.iter_rows(min_row=5, min_col=3, max_col=3) for c in row if c.value not in (None, "")]
    assert blue and all(str(c.font.color.rgb)[-6:] == "0000FF" for c in blue)
    # formulas reference Inputs, never embed their own constants: the audit's rule, spot-checked
    assert wb["Forecast"]["C10"].value.startswith("=")
    assert "static, generated by" in " ".join(str(c.value) for row in wb["Sensitivity"].iter_rows() for c in row if c.value)
    assert "seed" in " ".join(str(c.value) for row in wb["MonteCarlo_Summary"].iter_rows() for c in row if c.value).lower()


